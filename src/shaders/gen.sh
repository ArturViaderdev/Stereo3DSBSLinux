#!/bin/sh
# Regenerates ../depth3d_spv.h from depth3d.comp and ../weave_spv.h from weave.comp (needs
# glslangValidator). The headers are committed, so building the layer does not need glslang.
set -e
cd "$(dirname "$0")"
T="${TMPDIR:-/tmp}"
for p in 0 1 2; do glslangValidator -V --target-env vulkan1.2 -DPASS=$p depth3d.comp -o "$T/depth3d_$p.spv" >/dev/null; done
glslangValidator -V --target-env vulkan1.0 weave.comp -o "$T/weave.spv" >/dev/null
python3 - "$T" <<'PY'
import struct, sys
t = sys.argv[1]
def emit(path, items, src):
    out = [f"// generated by src/shaders/gen.sh from {src} - do not edit", "#pragma once", "#include <cstdint>"]
    for f, name in items:
        d = open(f"{t}/{f}", "rb").read()
        w = struct.unpack(f"<{len(d)//4}I", d)
        out.append(f"static const uint32_t {name}[] = {{")
        for i in range(0, len(w), 8):
            out.append("  " + ", ".join(f"0x{x:08x}u" for x in w[i:i+8]) + ",")
        out.append("};")
    open(path, "w").write("\n".join(out) + "\n")
emit("../depth3d_spv.h", [("depth3d_0.spv", "kDepthSplatSpv"), ("depth3d_1.spv", "kDepthResolveSpv"),
                          ("depth3d_2.spv", "kDepthMatchSpv")], "depth3d.comp")
emit("../weave_spv.h", [("weave.spv", "kWeaveSpv")], "weave.comp")
PY
echo "OK -> src/depth3d_spv.h src/weave_spv.h"
